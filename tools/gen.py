"""Build generator: jump table, symbol table and source area.

Reads kernel/main.asm and its %includes in image order, collects every
function header (`; name: x`) and the ones marked `; patchable: yes`, and
writes:

  build/gen/jt.inc      jump table, one `dq` slot per patchable function
  build/gen/symtab.inc  symbol table records for every function
  build/gen/labels.inc  name and value of every label and equ, for Forge
  build/gen/src.bin     source area: header, directory, then the source text
                        of every file holding a patchable function

It fails the build if a patchable function is called or jumped to directly
anywhere instead of through its jump table slot.
"""
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "build", "gen")

SYM_NAME_MAX = 31
SRC_NAME_MAX = 31
SRC_MAGIC = b"VSRC"
SRC_FILES_MAX = 64                  # as in forge/source.asm
SRC_FILE = 2


def walk(path, seen):
    """Yields (file, line_no, offset, line) for main.asm with includes expanded."""
    if path in seen:
        return
    seen.add(path)
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        text = f.read()
    offset = 0
    for no, line in enumerate(text.splitlines(keepends=True), 1):
        m = re.match(r'\s*%include\s+"([^"]+)"', line)
        if m and not m.group(1).startswith("build/"):
            yield from walk(m.group(1), seen)
        else:
            yield path, no, offset, line
        offset += len(line.encode("utf-8"))


def main():
    files = {}
    funcs = []            # [name, file, header offset, patchable] in image order
    labels = []           # every top-level label and equ, for Forge
    pending = None
    for path, no, offset, line in walk("kernel/main.asm", set()):
        files.setdefault(path, None)
        m = re.match(r"(\w+)(?::|\s+(?:equ|db|dw|dd|dq|resb|resw|resd|resq|times)\b)", line)
        if m:
            labels.append(m.group(1))
        m = re.match(r";\s*name:\s*(\w+)", line)
        if m:
            pending = [m.group(1), path, offset, False]
            continue
        if pending and re.match(r";\s*patchable:\s*yes", line):
            pending[3] = True
            continue
        if pending and re.match(rf"{pending[0]}:", line):
            funcs.append(pending)
            pending = None
        elif pending and not line.startswith(";"):
            sys.exit(f"{path}:{no}: header for {pending[0]} is not followed by its label")

    patchable = [f for f in funcs if f[3]]
    names = {f[0] for f in patchable}
    bad = []
    for path in files:
        with open(os.path.join(ROOT, path), encoding="utf-8") as f:
            for no, line in enumerate(f, 1):
                code = line.split(";")[0]
                for target in re.findall(r"\b(?:call|j[a-z]+)\s+(\w+)\b", code):
                    if target in names:
                        bad.append(f"{path}:{no}: direct {line.strip()!r}, use [rel jt_{target}]")
    if bad:
        sys.exit("\n".join(bad))

    # Source area: header, a directory of SRC_FILES_MAX entries, then file
    # text back to back: the kernel modules, then the user files in files/.
    src_files = [(p, p, 0) for p in sorted({f[1] for f in patchable})]
    for name in sorted(os.listdir(os.path.join(ROOT, "files"))):
        src_files.append((name, os.path.join("files", name), SRC_FILE))
    assert len(src_files) <= SRC_FILES_MAX
    blobs, base = [], {}
    pos = 16 + 48 * SRC_FILES_MAX
    for name, path, flags in src_files:
        with open(os.path.join(ROOT, path), "rb") as f:
            data = f.read()
        base[path] = pos
        blobs.append((name, pos, data, flags))
        pos += len(data)
    area = bytearray(SRC_MAGIC + struct.pack("<III", len(src_files), pos, 0))
    for name, start, data, flags in blobs:
        assert len(name) <= SRC_NAME_MAX, name
        area += name.encode().ljust(32, b"\0") + struct.pack("<IIQ", start, len(data), flags)
    area += bytes(48 * (SRC_FILES_MAX - len(src_files)))
    for _, _, data, _ in blobs:
        area += data

    os.makedirs(OUT, exist_ok=True)
    jt = ["; generated by tools/gen.py from `; patchable: yes` headers", "align 8", "jump_table:"]
    for f in patchable:
        jt.append(f"jt_{f[0]}: dq {f[0]}")
    jt.append(f"JT_COUNT equ {len(patchable)}")

    sym = ["; generated by tools/gen.py: one 64-byte record per function, in image order",
           "; +0 address, +8 size, +16 jump table slot (-1 if none),",
           "; +20 offset of its header in the source area (-1 if not embedded), +32 name",
           "align 8", "sym_table:"]
    slots = {f[0]: i for i, f in enumerate(patchable)}
    for i, (name, path, offset, _) in enumerate(funcs):
        assert len(name) <= SYM_NAME_MAX, name
        end = funcs[i + 1][0] if i + 1 < len(funcs) else "kernel_end_magic"
        src = base[path] + offset if path in base else -1
        sym.append(f"    dq {name}, {end} - {name}")
        sym.append(f"    dd {slots.get(name, -1)}, {src}, 0, 0")
        sym.append(f'    db "{name}"')
        sym.append(f"    times 32 - {len(name)} db 0")
    sym.append(f"SYM_COUNT equ {len(funcs)}")

    lab = ["; generated by tools/gen.py: value, then zero-terminated name, per label",
           "; and equ in the image; an empty name ends the table", "lab_table:"]
    for name in labels + [f"jt_{f[0]}" for f in patchable]:
        lab.append(f'    dq {name}\n    db "{name}", 0')
    lab.append("    dq 0\n    db 0")

    def write(name, text):
        path = os.path.join(OUT, name)
        data = text.encode() if isinstance(text, str) else bytes(text)
        if os.path.exists(path) and open(path, "rb").read() == data:
            return
        with open(path, "wb") as f:
            f.write(data)

    write("jt.inc", "\n".join(jt) + "\n")
    write("symtab.inc", "\n".join(sym) + "\n")
    write("labels.inc", "\n".join(lab) + "\n")
    write("src.bin", area)


main()
