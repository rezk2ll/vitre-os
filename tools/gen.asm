; Build generator, a Linux x86-64 program run from the repo root before the
; kernel build. It walks kernel/main.asm through its %includes in image
; order, reads every function header (`; name: x`) and the ones marked
; `; patchable: yes`, and writes build/gen/jt.inc (a jump table slot per
; patchable function), build/gen/labels.inc (every label and equ, for
; Forge), build/gen/symtab.inc and build/gen/src.bin. A file is rewritten
; only when its content changes, so make rebuilds only what depends on it.

BITS 64
default rel

SYS_READ   equ 0
SYS_WRITE  equ 1
SYS_OPEN   equ 2
SYS_CLOSE  equ 3
SYS_MKDIR  equ 83
SYS_EXIT   equ 60
O_WRONLY_CREAT_TRUNC equ 0x241

MAX_FILES  equ 512
MAX_FUNCS  equ 8192
MAX_LABELS equ 32768

section .text
global _start
_start:
    lea rdi, [main_path]
    call walk
    call check_calls
    lea rdi, [dir_build]
    call mkdir
    lea rdi, [dir_gen]
    call mkdir
    call gen_jt
    call gen_labels
    call gen_src
    xor edi, edi
    mov eax, SYS_EXIT
    syscall

; gen_jt: build/gen/jt.inc
gen_jt:
    push rbx
    call out_reset
    lea rdi, [jt_head]
    call out_s
    xor ebx, ebx
.func:
    cmp rbx, [funcs_n]
    jae .end
    lea rax, [func_patch]
    cmp byte [rax + rbx], 0
    je .next
    lea rdi, [s_jt]
    call out_s
    mov rdi, rbx
    call out_func
    lea rdi, [s_jt_dq]
    call out_s
    mov rdi, rbx
    call out_func
    mov edi, 10
    call out_c
    inc qword [jt_n]
.next:
    inc rbx
    jmp .func
.end:
    lea rdi, [s_jt_count]
    call out_s
    mov rdi, [jt_n]
    call out_dec
    mov edi, 10
    call out_c
    lea rdi, [path_jt]
    call out_write
    pop rbx
    ret

; gen_labels: build/gen/labels.inc
gen_labels:
    push rbx
    call out_reset
    lea rdi, [lab_head]
    call out_s
    xor ebx, ebx
.label:
    cmp rbx, [labels_n]
    jae .slots
    lea rax, [label_ptr]
    mov rdi, [rax + rbx * 8]
    lea rax, [label_len]
    mov rsi, [rax + rbx * 8]
    call out_label
    inc rbx
    jmp .label
.slots:
    xor ebx, ebx
.func:
    cmp rbx, [funcs_n]
    jae .end
    lea rax, [func_patch]
    cmp byte [rax + rbx], 0
    je .next
    lea rdi, [s_lab_dq]
    call out_s
    lea rdi, [s_jt]
    call out_s
    mov rdi, rbx
    call out_func
    lea rdi, [s_lab_db]
    call out_s
    lea rdi, [s_jt]
    call out_s
    mov rdi, rbx
    call out_func
    lea rdi, [s_lab_end]
    call out_s
.next:
    inc rbx
    jmp .func
.end:
    lea rdi, [lab_tail]
    call out_s
    lea rdi, [path_labels]
    call out_write
    pop rbx
    ret

; out_func(rdi = function index): its name appended to the output
out_func:
    lea rax, [func_len]
    mov rsi, [rax + rdi * 8]
    lea rax, [func_name]
    mov rdi, [rax + rdi * 8]
    jmp out_m

; out_label(rdi = name, rsi = length): its two lines of labels.inc
out_label:
    push rbx
    push r12
    push r13
    mov rbx, rdi
    mov r12, rsi
    lea rdi, [s_lab_dq]
    call out_s
    mov rdi, rbx
    mov rsi, r12
    call out_m
    lea rdi, [s_lab_db]
    call out_s
    mov rdi, rbx
    mov rsi, r12
    call out_m
    lea rdi, [s_lab_end]
    call out_s
    pop r13
    pop r12
    pop rbx
    ret

%include "tools/genscan.asm"
%include "tools/genio.asm"
%include "tools/gentext.asm"
%include "tools/gencheck.asm"
%include "tools/gensrc.asm"

section .data
main_path      db "kernel/main.asm", 0
dir_build      db "build", 0
dir_gen        db "build/gen", 0
path_jt        db "build/gen/jt.inc", 0
path_labels    db "build/gen/labels.inc", 0
kw_include     db "%include"
kw_name        db "name:"
kw_patchable   db "patchable:"
kw_yes         db "yes"
keywords       db 3, "equ", 2, "db", 2, "dw", 2, "dd", 2, "dq", 4, "resb"
               db 4, "resw", 4, "resd", 4, "resq", 5, "times", 0
msg_header     db "header for ", 0
msg_unfollowed db " is not followed by its label", 10, 0
jt_head        db "; generated by tools/gen.asm from `; patchable: yes` headers", 10
               db "align 8", 10, "jump_table:", 10, 0
s_jt           db "jt_", 0
s_jt_dq        db ": dq ", 0
s_jt_count     db "JT_COUNT equ ", 0
lab_head       db "; generated by tools/gen.asm: value, then zero-terminated name, per label", 10
               db "; and equ in the image; an empty name ends the table", 10
               db "lab_table:", 10, 0
s_lab_dq       db "    dq ", 0
s_lab_db       db 10, '    db "', 0
s_lab_end      db '", 0', 10, 0
lab_tail       db "    dq 0", 10, "    db 0", 10, 0

section .bss
files_n      resq 1
file_path    resq MAX_FILES
file_text    resq MAX_FILES
file_len     resq MAX_FILES
funcs_n      resq 1
func_name    resq MAX_FUNCS
func_len     resq MAX_FUNCS
func_file    resq MAX_FUNCS
func_off     resq MAX_FUNCS
func_patch   resb MAX_FUNCS
labels_n     resq 1
label_ptr    resq MAX_LABELS
label_len    resq MAX_LABELS
jt_n         resq 1
cur_file     resq 1
cur_no       resq 1
cur_off      resq 1
pend_name    resq 1
pend_len     resq 1
pend_file    resq 1
pend_off     resq 1
pend_on      resb 1
pend_patch   resb 1
